"""
Stage 2 of the split benchmark pipeline.

Runs LLM inference on graphs pre-generated by generate_graphs.py (Stage 1)
and evaluates answers against ground truth.

Input : JSONL produced by generate_graphs.py
Output: JSONL results file (same format as evaluate_*.py scripts)
"""

import os
import sys
import json
import time
import math
import asyncio
import argparse
import datetime
import networkx as nx
from tqdm import tqdm
from typing import List, Any, Iterator, Tuple

os.environ["TOKENIZERS_PARALLELISM"] = "false"
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from mas_framework.graph.graph import TestGraph
from mas_framework.utils.globals import Cost, PromptTokens, CompletionTokens
from experiment.utils import convert_to_pyg_graph
from experiment.eval_checkpoint import load_checkpoint, log_batch


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args():
    p = argparse.ArgumentParser(
        description="Benchmark with pre-generated ARGDesigner graphs (Stage 2)")
    p.add_argument('--graphs_file', type=str, required=True,
                   help="JSONL file produced by generate_graphs.py")
    p.add_argument('--dataset', type=str, required=True,
                   choices=['gsm8k', 'aqua', 'humaneval', 'mmlu', 'multiarith', 'svamp'])
    p.add_argument('--llm_name', type=str, default='Qwen/Qwen3-8B')
    p.add_argument('--decision_method', type=str, default='FinalRefer')
    p.add_argument('--output_file', type=str, required=True)
    p.add_argument('--summary_log_file', type=str,
                   default='./res_logs/evaluation_summary.jsonl')
    p.add_argument('--limit', type=int, default=None)
    p.add_argument('--eval_batch_size', type=int, default=8)
    p.add_argument('--model_type', type=str, default=None,
                   help="Graph generator label (read from graphs file if absent)")
    return p.parse_args()


# ---------------------------------------------------------------------------
# Graph deserialisation
# ---------------------------------------------------------------------------

def deserialize_graph(d: dict) -> nx.DiGraph:
    G = nx.DiGraph()
    for node in d['nodes']:
        G.add_node(int(node['id']), role=node['role'])
    for u, v in d['edges']:
        G.add_edge(int(u), int(v))
    return G


def apply_role_constraints(g: nx.DiGraph, role_description: dict) -> nx.DiGraph:
    for n in g.nodes():
        role = g.nodes[n].get('role', 'Unknown')
        g.nodes[n]['constraint'] = role_description.get(role, '')
    return g


# ---------------------------------------------------------------------------
# Per-dataset helpers
# ---------------------------------------------------------------------------

def get_role_description(dataset: str) -> dict:
    if dataset in ('gsm8k', 'multiarith', 'svamp'):
        from experiment.gsm8k.gsm8k_prompt_set import ROLE_DESCRIPTION
    elif dataset == 'aqua':
        from experiment.aqua.aqua_prompt_set import ROLE_DESCRIPTION
    elif dataset == 'humaneval':
        from experiment.humaneval.humaneval_prompt_set import ROLE_DESCRIPTION
    elif dataset == 'mmlu':
        from experiment.mmlu.mmlu_prompt_set import ROLE_DESCRIPTION
    else:
        raise ValueError(f"Unknown dataset: {dataset}")
    return ROLE_DESCRIPTION  # noqa: F821


def evaluate_prediction(dataset: str, raw_answer, true_answer: str) -> Tuple[str, bool]:
    """Return (predicted_for_display, is_solved)."""
    raw_str = str(raw_answer)

    if dataset in ('gsm8k', 'multiarith', 'svamp'):
        from benchmark_datasets.gsm8k_dataset import gsm_get_predict
        predicted = gsm_get_predict(raw_str)
        try:
            is_solved = float(predicted) == float(true_answer)
        except (ValueError, TypeError):
            is_solved = False
        return predicted, is_solved

    elif dataset == 'aqua':
        from benchmark_datasets.aqua_dataset import aqua_get_predict
        predicted = aqua_get_predict(raw_str)
        return predicted, (predicted == true_answer)

    elif dataset == 'humaneval':
        from mas_framework.tools.coding.python_executor import PyExecutor
        code = raw_str.lstrip("```python\n").rstrip("\n```")
        is_solved, _, _ = PyExecutor().execute(code, [true_answer], timeout=100)
        return code, is_solved

    elif dataset == 'mmlu':
        # Mirror MMLUDataset.postprocess_answer (no instance state needed)
        answer = raw_str
        if isinstance(raw_answer, list):
            answer = raw_answer[0] if raw_answer else ''
        ans_pos = answer.find("answer is")
        if ans_pos != -1:
            answer = answer[ans_pos + len("answer is"):].strip(":").strip().strip("Option").strip()
        predicted = answer[0] if answer else ''
        return predicted, (predicted == true_answer)

    return raw_str, False


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

async def main():
    args = parse_args()

    Cost.instance().reset()
    PromptTokens.instance().reset()
    CompletionTokens.instance().reset()

    # Load pre-generated graphs (skip entries where graph generation failed)
    print(f"Loading graphs from {args.graphs_file} ...")
    graphs_data: List[dict] = []
    with open(args.graphs_file, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line:
                r = json.loads(line)
                if r.get('graph') is not None:
                    graphs_data.append(r)
                else:
                    print(f"  Skipping {r.get('task_id')} — no graph (generation error).")
    if args.limit:
        graphs_data = graphs_data[:args.limit]

    # Determine model_type: CLI arg > first record in file > fallback
    if args.model_type:
        model_type = args.model_type
    elif graphs_data:
        model_type = graphs_data[0].get('model_type', 'unknown')
    else:
        model_type = 'unknown'

    print("=" * 60)
    print(f"  Graph generator  : {model_type.upper()}")
    print(f"  Graphs file      : {args.graphs_file}")
    print(f"  LLM              : {args.llm_name}")
    print(f"  Dataset          : {args.dataset}")
    print(f"  Valid graphs     : {len(graphs_data)}")
    print("=" * 60)

    role_description = get_role_description(args.dataset)
    total_tasks = len(graphs_data)
    os.makedirs(os.path.dirname(args.output_file) or '.', exist_ok=True)
    _, done_ids, solved_tasks = load_checkpoint(args.output_file)
    total_done = len(done_ids)
    _wall_start = time.time()

    def batch_iter(data: List[Any], size: int) -> Iterator[List[Any]]:
        buf = []
        for item in data:
            buf.append(item)
            if len(buf) >= size:
                yield buf
                buf = []
        if buf:
            yield buf

    def _append_result(out_fh, rec: dict) -> None:
        """Write one result line immediately and flush to disk."""
        out_fh.write(json.dumps(rec) + '\n')
        out_fh.flush()
        os.fsync(out_fh.fileno())

    num_batches = math.ceil(total_tasks / args.eval_batch_size)
    pbar = tqdm(enumerate(batch_iter(graphs_data, args.eval_batch_size)),
                total=num_batches, desc=f"Benchmarking [{args.dataset}]")

    # Open in append mode — results written per-sample survive mid-batch crashes.
    with open(args.output_file, 'a', encoding='utf-8') as out_fh:
        for i_batch, batch in pbar:
            answer_tasks = []
            metadata = []
            prep_errors = []
            _batch_start = time.time()

            for rec in batch:
                task_id = rec['task_id']
                if task_id in done_ids:
                    continue

                task_text = rec['task_text']
                true_answer = rec['true_answer']

                try:
                    g = deserialize_graph(rec['graph'])
                    apply_role_constraints(g, role_description)
                    pyg_data = convert_to_pyg_graph(g, task_text)
                    tg = TestGraph(domain=args.dataset, llm_name=args.llm_name,
                                   decision_method=args.decision_method, pyg_data=pyg_data)
                    answer_tasks.append(tg.arun({'task': task_text}, num_rounds=1))
                    metadata.append({
                        'task_id': task_id,
                        'task_text': task_text,
                        'true_answer': true_answer,
                        'num_nodes': rec.get('num_nodes', g.number_of_nodes()),
                        'num_edges': rec.get('num_edges', g.number_of_edges()),
                    })
                except Exception as e:
                    print(f"Error preparing {task_id}: {e}")
                    err_rec = {
                        'task_id': task_id, 'question': task_text,
                        'true_answer': true_answer, 'predicted_answer': None,
                        'is_solved': False, 'error': str(e),
                    }
                    _append_result(out_fh, err_rec)
                    done_ids.add(str(task_id))
                    total_done += 1
                    prep_errors.append(err_rec)

            if not answer_tasks:
                continue

            all_results = await asyncio.gather(*answer_tasks, return_exceptions=True)

            for i, result in enumerate(all_results):
                meta = metadata[i]
                if isinstance(result, Exception):
                    print(f"Error executing {meta['task_id']}: {result}")
                    err_rec = {
                        'task_id': meta['task_id'], 'question': meta['task_text'],
                        'true_answer': meta['true_answer'], 'predicted_answer': None,
                        'is_solved': False, 'error': str(result),
                    }
                    _append_result(out_fh, err_rec)
                    done_ids.add(str(meta['task_id']))
                    total_done += 1
                    continue

                raw = result[0] if isinstance(result, list) and result else result
                predicted, is_solved = evaluate_prediction(args.dataset, raw, meta['true_answer'])
                if is_solved:
                    solved_tasks += 1
                res_rec = {
                    'task_id': meta['task_id'],
                    'question': meta['task_text'],
                    'true_answer': meta['true_answer'],
                    'predicted_answer': predicted,
                    'raw_response': str(raw),
                    'is_solved': is_solved,
                    'num_nodes': meta['num_nodes'],
                    'num_edges': meta['num_edges'],
                }
                _append_result(out_fh, res_rec)
                done_ids.add(str(meta['task_id']))
                total_done += 1

            acc = solved_tasks / total_done * 100 if total_done else 0
            pbar.set_postfix({
                'Accuracy': f'{acc:.2f}% ({solved_tasks}/{total_done})',
                'Tokens': f'${PromptTokens.instance().value:.4f}',
            })
            log_batch(i_batch, num_batches, solved_tasks, total_done, total_tasks,
                      time.time() - _batch_start, _wall_start)

    pass_at_1 = solved_tasks / total_done * 100 if total_done > 0 else 0
    final_cost = Cost.instance().value
    final_prompt = PromptTokens.instance().value
    final_completion = CompletionTokens.instance().value

    print(f"\n{'='*50}\nBenchmark Summary [{args.dataset}]")
    print(f"LLM        : {args.llm_name}")
    print(f"Graphs file: {args.graphs_file}")
    print(f"Total: {total_done}  Solved: {solved_tasks}  Pass@1: {pass_at_1:.2f}%")
    print(f"Cost: ${final_cost:.6f}  "
          f"Prompt tokens: {int(final_prompt)}  "
          f"Completion tokens: {int(final_completion)}")
    print(f"Results saved to: {args.output_file}")

    log_record = {
        'timestamp': datetime.datetime.now().isoformat(),
        'dataset': args.dataset,
        'model_type': model_type,
        'llm_name': args.llm_name,
        'graphs_file': args.graphs_file,
        'total_tasks': total_done,
        'solved_tasks': solved_tasks,
        'pass_at_1': pass_at_1,
        'cost': final_cost,
        'prompt_tokens': final_prompt,
        'completion_tokens': final_completion,
        'detail_file': args.output_file,
    }
    try:
        os.makedirs(os.path.dirname(args.summary_log_file) or '.', exist_ok=True)
        with open(args.summary_log_file, 'a', encoding='utf-8') as f:
            f.write(json.dumps(log_record) + '\n')
    except Exception as e:
        print(f"Failed to write summary log: {e}")
    print('=' * 50)


if __name__ == '__main__':
    if sys.platform == 'win32':
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    asyncio.run(main())
